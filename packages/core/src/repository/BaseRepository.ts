import { Store } from 'tinybase';
import * as path from 'path';
import logger from '../logger';
import { FileSystemAdapter } from './FileSystemAdapter';
import { IRepository, SaveResult, EntityConfig } from './types';

/**
 * Generic repository for any entity type
 * Implements common CRUD operations following DRY principle
 */
export class BaseRepository<T> implements IRepository<T> {
  constructor(
    private store: Store,
    private fileSystem: FileSystemAdapter,
    private config: EntityConfig<T>,
    private productRoots: string[]
  ) {}

  /**
   * Load all entities from all product roots
   * For product entities (functions, workflows, etc.), this is called with specific directories
   * For config entities (projects, apps), this loads from CONFIG_ROOTS
   */
  async loadAll(): Promise<number> {
    let totalLoaded = 0;

    // If no productRoots specified, this is a product entity that will be loaded from app directories
    // Only load from productRoots if they are specified (for config entities)
    if (this.productRoots.length === 0) {
      return 0; // Product entities are loaded separately from app directories
    }

    for (const productRoot of this.productRoots) {
      const entityPath = path.resolve(productRoot, this.config.subdirectory);

      if (this.fileSystem.directoryExists(entityPath)) {
        const files = this.fileSystem.getAllYamlFiles(entityPath);
        logger.info(
          `Found ${files.length} ${this.config.tableName} YAML files in ${entityPath}`
        );

        totalLoaded += files.length;

        for (const file of files) {
          await this.loadFile(file);
        }
      } else {
        logger.info(`${this.config.subdirectory} directory does not exist, creating`, {
          path: entityPath,
        });
        this.fileSystem.ensureDirectoryExists(entityPath);
      }
    }

    return totalLoaded;
  }

  /**
   * Load single file
   */
  async loadFile(filePath: string): Promise<void> {
    const data = this.fileSystem.loadYamlFile<T>(filePath);

    if (!data) {
      return;
    }

    this.loadData(data, filePath);
  }

  /**
   * Put an entity that was not read from its own YAML file (e.g. from a project manifest) into the store
   */
  loadData(data: T, filePath: string, validate = true): void {
    // Validate required fields (skipped for entities generated by Product Creator itself)
    const validationError = validate ? this.config.validateRequired(data) : null;
    if (validationError) {
      logger.warn(validationError, { filePath });
      return;
    }

    // Store in TinyBase
    const id = this.config.getIdField(data);
    const row = this.config.toRow(data, filePath);

    this.store.setRow(this.config.tableName, id, row as Record<string, string | number | boolean>);

    logger.debug(`Loaded ${this.config.tableName}`, { id, filePath });
  }

  /**
   * Get all entities
   */
  getAll(): T[] {
    const table = this.store.getTable(this.config.tableName);
    return Object.values(table).map((row) => this.config.fromRow(row));
  }

  /**
   * Get entity by ID
   */
  getById(id: string): T | null {
    const row = this.store.getRow(this.config.tableName, id);
    if (!row || !row[Object.keys(row)[0]]) return null;

    return this.config.fromRow(row);
  }

  /**
   * Save entity
   */
  async save(data: T, targetRoot?: string): Promise<SaveResult> {
    try {
      // Validate required fields
      const validationError = this.config.validateRequired(data);
      if (validationError) {
        logger.error(validationError);
        return { success: false, error: validationError };
      }

      // Validate targetRoot
      if (!targetRoot) {
        logger.error('Target root directory is required');
        return { success: false, error: 'Target root directory is required' };
      }

      // For config entities (projects, apps), validate against CONFIG_ROOTS
      // For product entities (functions, workflows, etc.), accept any valid directory path
      if (this.productRoots.length > 0 && !this.productRoots.includes(targetRoot)) {
        logger.error('Invalid target root', {
          targetRoot,
          availableRoots: this.productRoots,
        });
        return { success: false, error: 'Invalid target root directory' };
      }

      // Calculate file path (use custom path builder if provided)
      const newFilePath = this.config.getFilePath
        ? this.config.getFilePath(data, targetRoot, this.config.subdirectory)
        : path.resolve(targetRoot, this.config.subdirectory, this.config.getFileName(data));

      // Check for duplicate ID with different path
      const id = this.config.getIdField(data);
      const existing = this.store.getRow(this.config.tableName, id);

      if (existing && existing.filePath) {
        // Normalize both paths for proper comparison
        // Use normalize after resolve to handle edge cases like trailing slashes, ./, ../
        const existingFilePath = path.normalize(path.resolve(existing.filePath as string));
        const normalizedNewPath = path.normalize(path.resolve(newFilePath));

        // Compare paths (case-insensitive on case-insensitive file systems like macOS/Windows)
        // On case-sensitive systems (Linux), this will still work correctly
        const pathsMatch = 
          existingFilePath === normalizedNewPath ||
          existingFilePath.toLowerCase() === normalizedNewPath.toLowerCase();

        if (!pathsMatch) {
          // Paths are different but ID matches - this is a file rename/migration scenario
          // This can happen when:
          // 1. File was created with wrong name and needs to be renamed to match ID
          // 2. Entity ID changed and file needs to be moved/renamed
          // Allow the update by deleting the old file and saving to the new path
          logger.info(`Renaming ${this.config.tableName} file to match ID`, {
            id,
            oldPath: existingFilePath,
            newPath: normalizedNewPath,
          });
          
          // Delete the old file since we're migrating to the new path
          this.fileSystem.deleteFile(existingFilePath);
          
          // Remove the old entry from store (it will be reloaded with new path after save)
          this.store.delRow(this.config.tableName, id);
        } else {
          // Paths match - this is an update to the same file, allow it
          logger.debug(`Updating existing ${this.config.tableName}`, {
            id,
            filePath: normalizedNewPath,
          });
        }
      }

      // Save file
      const saved = this.fileSystem.saveYamlFile(newFilePath, data);

      if (!saved) {
        return { success: false, error: 'Failed to write file' };
      }

      // Reload into store
      await this.loadFile(newFilePath);

      return { success: true };
    } catch (error) {
      logger.error(`Failed to save ${this.config.tableName}`, { error });
      return { success: false, error: String(error) };
    }
  }

  /**
   * Remove entity from store by file path
   */
  removeByFilePath(filePath: string): boolean {
    const table = this.store.getTable(this.config.tableName);

    for (const [id, data] of Object.entries(table)) {
      if (data.filePath === filePath) {
        this.store.delRow(this.config.tableName, id);
        logger.debug(`Removed ${this.config.tableName}`, { id, filePath });
        return true;
      }
    }

    return false;
  }
}
