const CATALOGS: Record<string, Messages> = { en, ru, de };

export const FALLBACK_LANGUAGE = 'en';

/** Labels for a language tag (`pt-BR` → `pt-BR`, then `pt`, then English) */
export function messagesFor(language: string): { messages: Messages; language: string; fallback: boolean } {
  const tag = language.trim();
  for (const candidate of [tag, tag.split('-')[0].toLowerCase()]) {
    if (CATALOGS[candidate]) return { messages: CATALOGS[candidate], language: candidate, fallback: false };
  }
  return { messages: CATALOGS[FALLBACK_LANGUAGE], language: FALLBACK_LANGUAGE, fallback: true };
}

/** Languages that have label catalogs */
export const specLanguages = (): string[] => Object.keys(CATALOGS);
